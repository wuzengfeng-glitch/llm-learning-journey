show("旋转 90°", rotate, expected_hint="(期望1)")


# ---------- 3. 剪切矩阵 [[1,1],[0,1]]（反直觉但要记住！） ----------
# TODO: 填进去，观察 det
# 几何：i-hat 不动 (1,0)，j-hat 从 (0,1) 滑到 (1,1) → 平行四边形
# 底 × 高 还是 1×1 = 1，所以 det 应该是 ?
shear = np.array([[1, 1], [0, 1]])
show("剪切 [[1,1],[0,1]]", shear, expected_hint="(期望 1，保面积)")


# ---------- 4. 压扁矩阵 [[1,2],[2,4]]（两列线性相关） ----------
# TODO: 填进去
