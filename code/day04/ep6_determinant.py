"""EP6 — 行列式

看完视频后在这里验证（都用 np.linalg.det）：
- 缩放矩阵 [[2,0],[0,3]] → det = 6（面积放大 6 倍）
- 旋转矩阵 [[0,-1],[1,0]] → det = 1（保面积，只改朝向）
- 剪切矩阵 [[1,1],[0,1]] → det = 1（**保面积！** 反直觉但重要）
- 压扁矩阵 [[1,2],[2,4]]（两列共线）→ det = 0（面积压成一条线 → 不可逆）
- 翻转矩阵 [[-1,0],[0,1]] → det = -1（负号 = 朝向翻转，像左右手互换）

3D 里 det 是**体积**缩放因子（含符号）。

关键结论：det = 0 ⇔ 矩阵不可逆 ⇔ 列向量线性相关 ⇔ 空间被"压扁"到更低维度。
"""
import numpy as np


def show(name, M, expected_hint=""):
    """跑一个矩阵，打印它、它的 det、面积几何意义。"""
    det = np.linalg.det(M)
    print(f"--- {name} ---")
    print("M =\n", M)
    print(f"det(M) = {det:.4f}   {expected_hint}")
    print()


# ---------- 1. 缩放矩阵：横向 ×2，纵向 ×3 ----------
# 几何：单位正方形（面积 1）被拉成 2×3 的矩形（面积 6）
# 所以 det 应该 = 2 * 3 = 6
scale = np.array([[2, 0],
                  [0, 3]])
show("缩放 [[2,0],[0,3]]", scale, expected_hint="(期望 6，面积放大 6 倍)")


# ---------- 2. 旋转 90°：i-hat 变 (0,1)，j-hat 变 (-1,0) ----------
# TODO: 自己填这个矩阵，跑 show(...)
