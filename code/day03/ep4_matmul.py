"""EP4 — 矩阵乘法与线性复合

看完视频后在这里验证：
- 造两个变换 A（旋转）和 B（剪切），比较 A @ B 与 B @ A（一般不等 → 复合顺序有几何意义）
- 验证 (A @ B) @ v == A @ (B @ v)（"先做 B 再做 A"等价于用复合矩阵一次作用）
- 感受"矩阵乘法读法：从右往左"——右边先作用

踩的坑（第一版犯的错，改后留个记号，防止再犯）：
1. v 写成了 2×2 矩阵 [[1,1],[2,2]] —— 应该是向量 shape (2,)。
   矩阵结合律对矩阵也成立，代码"能跑"但几何画面丢了：
   视频里 v 是一个具体的箭头，要看它被"先 B 剪一下、再 A 转一下"落到哪。
2. 只算了 (A@B)@v == A@(B@v)（结合律，两种写法一定相等）—— 漏了
   (A@B)@v vs (B@A)@v（不同顺序，结果不同），后者才是"AB≠BA 的几何意义"。
3. 只 print 了 AB 和 BA 两个矩阵，没显式给结论。用 np.array_equal 直接判 False 更醒目。
4. 命名：DifAB 看着像"差"（difference），其实是乘积 A@B；U1/u2 大小写混用。
"""
import numpy as np

A = np.array([[0, -1], [1, 0]])   # 90° 逆时针旋转
B = np.array([[1, 1], [0, 1]])    # 水平剪切（y 不变，x 被 y 拉动）

print("A =\n", A)
print("B =\n", B)

# —— 验证 1：AB ≠ BA（矩阵乘法不满足交换律） ——
AB = A @ B
BA = B @ A
print("\nA @ B =\n", AB)
print("B @ A =\n", BA)
print("A @ B == B @ A ?", np.array_equal(AB, BA))   # False → 顺序有几何意义

# —— 验证 2：结合律 (A@B)@v == A@(B@v)（同一种顺序的两种写法） ——
v = np.array([1, 1])
u1 = (A @ B) @ v
u2 = A @ (B @ v)
print("\n(A @ B) @ v =", u1)
print("A @ (B @ v) =", u2, "  ← 与上一行相等，说明结合律成立")

# —— 验证 3：不同顺序 → 不同结果（"从右往左"读法的核心画面） ——
v_via_AB = (A @ B) @ v   # 读作: 先做 B（剪切），再做 A（旋转）
v_via_BA = (B @ A) @ v   # 读作: 先做 A（旋转），再做 B（剪切）
print("\n先 B 后 A: (A @ B) @ v =", v_via_AB)
print("先 A 后 B: (B @ A) @ v =", v_via_BA, "  ← 与上一行不同，顺序改变了几何终点")
