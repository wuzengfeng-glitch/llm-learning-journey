"""EP3 — 矩阵与线性变换

看完视频后在这里验证：
- 造一个 2x2 矩阵 M，把它的两列理解为"基向量 i, j 变换后的位置"
- 对任意向量 v，M @ v 应该等于 v[0]*M[:,0] + v[1]*M[:,1]（即 i, j 的线性组合）
- 试几个经典变换：90° 旋转矩阵 [[0,-1],[1,0]]、剪切 [[1,1],[0,1]]、缩放 [[2,0],[0,3]]
"""
import numpy as np

# —— 通用矩阵作用于向量 ——
M = np.array([[1, 2], [0, 3]])
v = np.array([4, 7])

print("M =\n", M)
print("v =", v)
print("M @ v =", M @ v)

# —— 验证 1：矩阵的列 = 基向量变换后的位置 ——
i_hat = np.array([1, 0])
j_hat = np.array([0, 1])
print("\nM @ i_hat =", M @ i_hat, "  应等于 M 第 0 列:", M[:, 0])
print("M @ j_hat =", M @ j_hat, "  应等于 M 第 1 列:", M[:, 1])

# —— 验证 2：M @ v = v[0]*(i 变换后) + v[1]*(j 变换后) ——
by_combination = v[0] * M[:, 0] + v[1] * M[:, 1]
print("\n拆成基向量的线性组合:", by_combination)
print("直接矩阵乘法        :", M @ v)

# —— 三个经典变换 ——
R = np.array([[0, -1], [1, 0]])   # 90° 逆时针旋转
S = np.array([[1, 1], [0, 1]])    # 水平剪切（y 不变，x 被 y 拉动）
D = np.array([[2, 0], [0, 3]])    # 缩放：x×2, y×3

print("\nR @ v =", R @ v, "  (90° 旋转: 第一象限 → 第二象限)")
print("S @ v =", S @ v, "  (剪切: y 保持 7 不变)")
print("D @ v =", D @ v, "  (缩放: x=4→8, y=7→21)")
